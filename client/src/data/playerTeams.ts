/** Look up a player's team. Case-insensitive, handles partial last-name matches. */
export function getPlayerTeam(playerName: string): string | null {
  if (!playerName) return null;
  const name = playerName.trim();

  // Exact match first
  if (PLAYER_TEAM[name]) return PLAYER_TEAM[name];

  // Case-insensitive exact
  const lower = name.toLowerCase();
  for (const [k, v] of Object.entries(PLAYER_TEAM)) {
    if (k.toLowerCase() === lower) return v;
  }

  // Last-name match (e.g. "Harden" → "James Harden")
  const parts = name.split(" ");
  const lastName = parts[parts.length - 1].toLowerCase();
  if (lastName.length >= 4) {
    for (const [k, v] of Object.entries(PLAYER_TEAM)) {
      const kParts = k.split(" ");
      if (kParts[kParts.length - 1].toLowerCase() === lastName) return v;
    }
  }

  return null;
}
